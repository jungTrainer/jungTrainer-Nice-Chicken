// Build-only adapter: one editable JSON, a deterministic browser catalog and optional SW assets.
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const IMAGE_MIME = { '.png':'image/png', '.jpg':'image/jpeg', '.jpeg':'image/jpeg', '.webp':'image/webp', '.svg':'image/svg+xml' };
function buildImageCatalog(root) {
  const config = JSON.parse(fs.readFileSync(path.join(root, 'assets/images/catalog.json'), 'utf8'));
  const object = v => !!v && typeof v === 'object' && !Array.isArray(v);
  if (!object(config) || config.version !== 1 || !object(config.entries) || !object(config.aliases) || !object(config.aliases.customers) || !object(config.aliases.vehicles)) throw Error('Invalid image catalog');
  const assets = new Map(), entries = {};
  for (const [id, entry] of Object.entries(config.entries)) {
    if (!/^[a-z0-9][a-z0-9_.-]{0,99}$/.test(id) || !object(entry) || !Array.isArray(entry.sources) || entry.sources.length > 4 || Object.keys(entry).some(k => !['sources','fit','anchor'].includes(k))) throw Error('Invalid image entry: '+id);
    const fit = entry.fit || 'contain', anchor = entry.anchor || [.5,.5];
    if (!['contain','cover'].includes(fit) || !Array.isArray(anchor) || anchor.length !== 2 || anchor.some(n => !Number.isFinite(n) || n<0 || n>1)) throw Error('Invalid image fit/anchor: '+id);
    const sources = entry.sources.map(file => {
      // Scope-relative assets only: no network URLs, query strings, traversal or symlinks.
      if (typeof file !== 'string' || !/^assets\/images\/(?:[a-zA-Z0-9_-]+\/)*[a-zA-Z0-9_.-]+\.(png|jpg|jpeg|webp|svg)$/.test(file) || file.includes('..')) throw Error('Invalid image path: '+file);
      const mime = IMAGE_MIME[path.extname(file)];
      if (!assets.has(file)) {
        const full = path.join(root, file);
        let digest = null;
        if (fs.existsSync(full)) {
          const real = fs.realpathSync(full), base = fs.realpathSync(path.join(root,'assets/images')) + path.sep;
          if (!real.startsWith(base) || !fs.statSync(real).isFile()) throw Error('Image outside asset directory: '+file);
          const bytes = fs.readFileSync(real);
          if (bytes.length > 8*1024*1024) throw Error('Image exceeds 8 MiB: '+file);
          digest = crypto.createHash('sha256').update(bytes).digest('hex');
        }
        assets.set(file,{path:file,hash:digest,mime});
      }
      return assets.get(file);
    });
    if (new Set(entry.sources).size !== entry.sources.length) throw Error('Repeated image candidate: '+id);
    entries[id] = {sources,fit,anchor};
  }
  for (const [group, aliases] of Object.entries(config.aliases)) {
    if (!['customers','vehicles'].includes(group) || !object(aliases) || Object.values(aliases).some(v => typeof v !== 'string' || !entries[(group==='customers'?'customer.':'vehicle.')+v])) throw Error('Invalid image aliases: '+group);
  }
  const data = {version:1,entries,aliases:config.aliases};
  const source = '// Generated by npm run pwa:build. Edit assets/images/catalog.json, not this file.\nconst IMAGE_CATALOG = (() => {\n  const data = '+JSON.stringify(data,null,2)+';\n  const freeze = value => { if (value && typeof value === "object") { Object.values(value).forEach(freeze); Object.freeze(value); } return value; };\n  return freeze(data);\n})();\n';
  return {source,assets:[...assets.values()]};
}
module.exports = {buildImageCatalog};
