async function verifiedResponse(asset) {
  const response = await fetch(assetURL(asset.path), {
    cache: "no-store",
    signal: AbortSignal.timeout(10000),
  });
  if (!response.ok || response.redirected || response.type === "opaque")
    throw Error(`PWA asset unavailable: ${asset.path}`);
  if (
    !(response.headers.get("content-type") || "")
      .toLowerCase()
      .includes(asset.mime)
  )
    throw Error(`PWA asset MIME mismatch: ${asset.path}`);
  const bytes = await response.arrayBuffer();
  const digest = await crypto.subtle.digest("SHA-256", bytes);
  const hex = [...new Uint8Array(digest)]
    .map((n) => n.toString(16).padStart(2, "0"))
    .join("");
  if (hex !== asset.hash) throw Error(`PWA asset hash mismatch: ${asset.path}`);
  const headers = new Headers(response.headers);
  headers.set("X-Nice-Chicken-Version", RELEASE.version);
  headers.set("Cache-Control", "no-store");
  return new Response(bytes, { status: 200, headers });
}

